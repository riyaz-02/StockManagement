/**
 * Makes the browser copy of the billing engine for the website's New bill screen (instant totals while typing):
 *   node scripts/gen-portal-calc.js          writes ../portal/public/assets/js/billing-calc.js
 *   node scripts/gen-portal-calc.js --check  exits 1 when that file is out of date
 * It is the SAME file as services/billingCalc.js wrapped for the browser, so the rules stay in one place. The server
 * always recalculates the bill when it is saved. Run this after changing services/billingCalc.js.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const src = fs.readFileSync(path.join(__dirname, '..', 'services', 'billingCalc.js'), 'utf8');
const out = `/* GENERATED by backend/scripts/gen-portal-calc.js from services/billingCalc.js: do not edit by hand. */\n(function () {\n'use strict';\nvar module = { exports: {} };\nvar exports = module.exports;\n${src}\nwindow.BillingCalc = module.exports;\n})();\n`;
const file = path.join(__dirname, '..', '..', 'portal', 'public', 'assets', 'js', 'billing-calc.js');
if (process.argv.includes('--check')) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (cur !== out) { console.error('portal billing-calc.js is out of date: run node scripts/gen-portal-calc.js'); process.exit(1); }
    console.log('portal billing-calc.js is up to date');
} else {
    fs.writeFileSync(file, out);
    console.log('written', file);
}
